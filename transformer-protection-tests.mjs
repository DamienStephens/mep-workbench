import assert from 'node:assert/strict';
import {transformerProtection,secondaryRuleConditions,transformerOcpdRatings} from './dist/transformer-protection.js';
const base={kva:15,phase:'3',primary:480,secondary:208,protection:'dual',primaryOcpd:0,secondaryOcpd:0,configuration:'three-phase-4-wire',secondaryRule:'10ft',lengthFt:8,installationConfirmed:true,designLoad:15000/(Math.sqrt(3)*208),material:'copper',terminal:75,ambient:30,parallelSets:1};
const calc=p=>transformerProtection({...base,...p});
const value=(r,label)=>r.results.find(x=>x.label===label)?.value;
const pass=p=>{const r=calc(p);assert.equal(r.error,undefined,r.error);return r;};
const fail=(p,re)=>assert.match(calc(p).error,re);
let r=pass({});
assert.equal(value(r,'Primary full-load current'),18.042);
assert.equal(value(r,'Secondary full-load current'),41.636);
assert.equal(value(r,'Selected primary OCPD'),20);
assert.equal(value(r,'Selected secondary OCPD'),45);
assert.equal(value(r,'Secondary phase conductor per set'),'6 AWG Cu');
assert.equal(value(r,'Combined usable phase ampacity'),60); // #8 55A × .8 =44A fails45A; #6 75A×.8=60A
r=pass({kva:7.5,phase:'1',secondary:240,configuration:'split-phase-3-wire',designLoad:31.25});
assert.equal(value(r,'Primary full-load current'),15.625);
assert.equal(value(r,'Secondary full-load current'),31.25);
assert.equal(value(r,'Selected primary OCPD'),20);
assert.equal(value(r,'Selected secondary OCPD'),35);
assert.equal(value(r,'Secondary phase conductor per set'),'8 AWG Cu'); // #10 small-conductor cap30
r=pass({kva:225,secondaryOcpd:800,primaryOcpd:600,designLoad:225000/(Math.sqrt(3)*208),parallelSets:3});
assert.equal(value(r,'Maximum modeled secondary transformer OCPD'),800);
assert.equal(value(r,'Secondary phase conductor per set'),'350 kcmil Cu');
assert.equal(value(r,'Combined usable phase ampacity'),840);
r=pass({kva:45,configuration:'three-phase-3-wire',designLoad:45000/(Math.sqrt(3)*208),primaryOcpd:125,secondaryOcpd:175});
assert.equal(value(r,'Maximum modeled primary OCPD'),125);
assert.equal(value(r,'Maximum modeled secondary transformer OCPD'),175);
assert.equal(value(r,'Secondary phase conductor per set'),'2/0 AWG Cu');
r=pass({kva:45,configuration:'three-phase-3-wire',designLoad:125,protection:'primary-only',primaryOcpd:70,secondaryOcpd:175});
assert.equal(value(r,'Maximum modeled primary OCPD'),70);
assert.match(value(r,'Maximum modeled secondary transformer OCPD'),/Not limited/);
fail({kva:45,primaryOcpd:150},/Primary 150 A.*250%/);
fail({kva:45,protection:'primary-only',primaryOcpd:80},/Primary 80 A.*125%/);
r=pass({kva:75,configuration:'three-phase-3-wire',designLoad:250,primaryOcpd:225,secondaryOcpd:300});
assert.equal(value(r,'Secondary phase conductor per set'),'350 kcmil Cu');
assert.equal(value(r,'Combined usable phase ampacity'),310);
assert.equal(value(r,'Maximum modeled secondary transformer OCPD'),300);
fail({kva:75,primaryOcpd:250},/Primary 250 A.*250%/);
fail({kva:75,secondaryOcpd:350},/Secondary 350 A.*125%/);
// A much smaller secondary load still must satisfy transformed primary-OCPD ratio floors.
r=pass({kva:45,configuration:'three-phase-3-wire',designLoad:10,primaryOcpd:100,secondaryOcpd:15});
assert.equal(value(r,'Required combined phase ampacity'),23.077);
assert.equal(value(r,'Secondary phase conductor per set'),'12 AWG Cu');
r=pass({kva:45,configuration:'three-phase-3-wire',designLoad:10,primaryOcpd:100,secondaryOcpd:15,secondaryRule:'25ft',lengthFt:25});
assert.equal(value(r,'Required combined phase ampacity'),76.923);
assert.equal(value(r,'Secondary phase conductor per set'),'4 AWG Cu');
// Primary-only Table450.3(B) exact thresholds and small-device unsupported range.
for(const [ip,percentage] of [[1.999,300],[2,167],[8.98,167]]){
 fail({kva:ip*.48,phase:'1',configuration:'single-phase-2-wire',protection:'primary-only',designLoad:1,primaryOcpd:15,secondaryOcpd:15},new RegExp(`${percentage}%`));
}
r=pass({kva:9*.48,phase:'1',configuration:'single-phase-2-wire',protection:'primary-only',designLoad:1,primaryOcpd:15,secondaryOcpd:15});
assert.equal(value(r,'Maximum modeled primary OCPD'),15);
assert.ok(r.steps.some(s=>s.includes('primary ceiling 125%')));
// Secondary <9 A uses 167% with no next-standard exception; exactly9 A permits125% next15.
fail({kva:8.98*.24,phase:'1',primary:120,secondary:240,configuration:'single-phase-2-wire',designLoad:1,primaryOcpd:20,secondaryOcpd:15},/Secondary 15 A.*167%/);
